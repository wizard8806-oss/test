#include "MacroInit.h"

/* Verified current fixed-three-pump/countdown PLC exports R2554=32. */
#define PANEL_MAP_VERSION 32u

/* Native Variable settings, in this order:
 * AlarmWords: Batch 16-Bit Unsigned Int, Bytes=10, R, FATEK R2550.
 * MapVersion: 16-Bit Unsigned Int, R, FATEK R2554.
 * BootAck: 16-Bit Unsigned Int, W, FATEK R2553.
 * Word0: actual alarms0..15. Word1: alarms16..23, startup bit8.
 * Word2: physical MANUAL selector state0/1; Word3: service word.
 * Word4: packed map version32, used through the alias below.
 * Word1 bits9..15: CL50S alarm generation, not alarm flags.
 * SKTool generates the symbols and their layout. Missing symbols are a
 * compile error rather than silently using assumed pVar byte offsets.
 */

#ifndef AlarmWords
#error Configure_AlarmWords_as_Batch_16_Bit_Unsigned_Int_R2550_Bytes10
#endif
#ifndef MapVersion
#error Configure_MapVersion_as_16_Bit_Unsigned_Int_R2554
#endif
#ifndef BootAck
#error Configure_BootAck_as_16_Bit_Unsigned_Int_W_R2553
#endif
#undef MapVersion
#define MapVersion ((unsigned short)AlarmWords[4])

static int WordAlarmBit(IN *p, int index)
{
    unsigned int value;
    value = index < 16 ? AlarmWords[0] : AlarmWords[1];
    return (int)((value >> (index & 15)) & 1u);
}

static unsigned int alarm_previous = 0u;
static int alarm_muted = 0;
static int alarm_started = 0;
/* CL50S shares the existing service word R2553:
 * 1 = informational boot acknowledgment; 256+generation = sound mute.
 * PLC publishes generation1..127 in reserved R2551 bits9..15.
 * Pending mute is tied to that generation, so a delayed write cannot
 * silence a newer alarm. No additional Variable settings are needed.
 */
static unsigned short cl50_previous_generation = 0u;
static unsigned short cl50_pending_generation = 0u;




/* LW50000..51993 is the vendor-documented power-off retention area.
 * Allocate only LW51000..51031: signature, count, five six-word dates.
 * Dates are newest first: year, month, day, hour, minute, second.
 */
static int helpers_started = 0;
static int boot_seen = 0;
static int manual_seen = 0;
static int manual_sync = 0;

static unsigned short InfoBCD(unsigned short value)
{
    return (unsigned short)((value & 15u) + ((value >> 4) & 15u) * 10u
        + ((value >> 8) & 15u) * 100u + ((value >> 12) & 15u) * 1000u);
}

static void PanelHelpers(IN *p)
{
    int i;
    int j;
    int boot;
    int manual;
    int clock_valid;
    unsigned short count;
    unsigned short stamp[6];

    if (!helpers_started) {
        LocalBit[810] = 0;
        if (LocalWord[51000] != 27128u || LocalWord[51001] > 5u) {
            for (i = 0; i < 32; ++i) {
                LocalWord[51000 + i] = 0;
            }
            LocalWord[51000] = 27128u;
        }
        helpers_started = 1;
    }

    BootAck = 0;
    if (!LocalBit[60107] || MapVersion != PANEL_MAP_VERSION) {
        LocalBit[810] = 0;
        manual_seen = 0;
        manual_sync = 0;
        return;
    }

    boot = ((AlarmWords[1] & 256u) != 0u);
    if (boot && !boot_seen) {
        /* System RTC words are BCD: second, minute, hour, day, month, year. */
        for (j = 0; j < 6; ++j) {
            stamp[j] = InfoBCD(LocalWord[60005 - j]);
        }
        clock_valid = (stamp[0] >= 2000u && stamp[0] <= 9999u
            && stamp[1] >= 1u && stamp[1] <= 12u
            && stamp[2] >= 1u && stamp[2] <= 31u
            && stamp[3] < 24u && stamp[4] < 60u && stamp[5] < 60u);
        if (clock_valid) {
            count = LocalWord[51001];
            for (i = 4; i > 0; --i) {
                for (j = 0; j < 6; ++j) {
                    LocalWord[51002 + i * 6 + j] = LocalWord[51002 + (i - 1) * 6 + j];
                }
            }
            for (j = 0; j < 6; ++j) {
                LocalWord[51002 + j] = stamp[j];
            }
            if (count < 5u) {
                LocalWord[51001] = (unsigned short)(count + 1u);
            }
            boot_seen = 1;
        }
    }
    if (!boot) {
        boot_seen = 0;
    }
    /* This word request only clears M1574; PLC consumes R2553 each scan. */
    BootAck = (unsigned short)(boot && boot_seen);

    manual = (AlarmWords[2] != 0u);
    /* The native PLC Control ignores its first sample. Publish zero for
     * one full macro tick before the first valid MANUAL request.
     */
    if (!manual_sync) {
        LocalBit[810] = 0;
        manual_seen = 0;
        manual_sync = 1;
    } else {
        if (manual && !manual_seen) {
            LocalBit[810] = 1;
        }
        if (!manual) {
            LocalBit[810] = 0;
        }
        manual_seen = manual;
    }
}

/* Read-only HMI decoration. Called once per existing 250 ms global macro tick.
 * Input symbols are generated by SKTool Variable settings; no pVar offsets.
 * This is VFD output-frequency indication, not a shaft/flow measurement.
 * LW900..902 frame, LW903..905 state, LW906..908 confirmed leader.
 */
#ifndef PumpAnimTelemetry
#error Configure_PumpAnimTelemetry_Batch16_R2500_Bytes26_ReadOnly
#endif
#ifndef PumpAnimRoles
#error Configure_PumpAnimRoles_Batch16_R2320_Bytes14_ReadOnly
#endif
#ifndef PumpAnimManual
#error Configure_PumpAnimManual_Batch16_R2380_Bytes6_ReadOnly
#endif
#ifndef PumpAnimLeader
#error Configure_PumpAnimLeader_UInt16_R2304_ReadOnly
#endif

static unsigned short pump_anim_phase[3] = {0u, 0u, 0u};
static unsigned short pump_anim_ticks[3] = {0u, 0u, 0u};

static void PumpAnimation(IN *p)
{
    int i;
    int valid;
    int running;
    int ready;
    int preparing;
    unsigned short frequency;
    unsigned short quality;
    unsigned short state;
    unsigned short divider;
    for (i = 0; i < 3; ++i) {
        frequency = PumpAnimTelemetry[i];
        quality = PumpAnimTelemetry[10 + i];
        valid = LocalBit[60107] && MapVersion == PANEL_MAP_VERSION
            && !(AlarmWords[0] & (1u << (9 + i)))
            && ((quality == 1u && frequency == 0u)
                || (quality == 2u && frequency > 0u && frequency <= 5990u));
        ready = !(AlarmWords[0] & (1u << (5 + i)));
        running = valid && ready && quality == 2u;
        preparing = AlarmWords[2] != 0u
            ? (PumpAnimManual[i] == 4u || PumpAnimManual[i] == 5u)
            : (PumpAnimRoles[i] == 5u || PumpAnimRoles[i] == 8u);
        state = !valid ? 0u : (!ready ? 4u : (running ? 2u : (preparing ? 3u : 1u)));
        LocalWord[903 + i] = state;
        LocalWord[906 + i] = (unsigned short)(valid && ready
            && PumpAnimLeader == (unsigned short)(i + 1)
            && PumpAnimRoles[4 + i] == 6u);
        if (!running) {
            pump_anim_phase[i] = 0u;
            pump_anim_ticks[i] = 0u;
            LocalWord[900 + i] = 0u;
        } else {
            /* Four blade orientations; 3, 2 or 1 macro ticks per frame.
             * Coarse visual tempo only: do not infer motor rpm from it.
             */
            divider = frequency < 200u ? 3u : (frequency < 350u ? 2u : 1u);
            LocalWord[900 + i] = (unsigned short)(1u + pump_anim_phase[i]);
            if (++pump_anim_ticks[i] >= divider) {
                pump_anim_ticks[i] = 0u;
                pump_anim_phase[i] = (unsigned short)((pump_anim_phase[i] + 1u) & 3u);
            }
        }
    }
}

void Macro_main(IN *p)
{
    unsigned int current;
    unsigned int rising;
    int i;
    int request;
    unsigned short cl50_generation;
    int cl50_new_generation;


    MarcoInit
    PumpAnimation(p);
    /* Diagnostic r8, packed WORD input before connection/version checks. */
    LocalWord[820] = 8u;
    LocalWord[821] = (unsigned short)((LocalWord[821] + 1u) % 60000u);
    LocalWord[822] = (LocalBit[60107] != 0);
    LocalWord[828] = MapVersion;
    LocalWord[823] = (AlarmWords[2] != 0u);
    LocalWord[824] = WordAlarmBit(p, 2);
    LocalWord[825] = ((AlarmWords[1] & 256u) != 0u);
    LocalWord[826] = 0u;
    LocalWord[827] = 0u;
    for (i = 0; i < 24; ++i) {
        if (WordAlarmBit(p, i)) {
            if (i < 16) {
                LocalWord[826] |= (unsigned short)(1u << i);
            } else {
                LocalWord[827] |= (unsigned short)(1u << (i - 16));
            }
        }
    }
    PanelHelpers(p);
    cl50_generation = (unsigned short)((AlarmWords[1] >> 9) & 127u);
    cl50_new_generation = 0;
    if (LocalBit[60107] && MapVersion == PANEL_MAP_VERSION && cl50_generation != 0u) {
        cl50_new_generation = (cl50_generation != cl50_previous_generation);
        cl50_previous_generation = cl50_generation;
    }


    if (!alarm_started) {
        alarm_previous = 0u;
        alarm_muted = 0;
        LocalBit[800] = 0;
        LocalBit[801] = 0;
        LocalBit[802] = 0;
        alarm_started = 1;
    }

    current = alarm_previous;
    if (LocalBit[60107] && MapVersion == PANEL_MAP_VERSION) {
        current = 0u;
        for (i = 0; i < 24; ++i) {
            if (WordAlarmBit(p, i)) {
                current |= (1u << i);
            }
        }
    }

    request = LocalBit[800];
    LocalBit[800] = 0;
    if (request && current != 0u) {
        alarm_muted = 1;
    }

    rising = current & ~alarm_previous;
    if (rising != 0u || current == 0u
            || (cl50_new_generation && current != 0u)) {
        alarm_muted = 0;
        cl50_pending_generation = 0u;
    } else if (request && current != 0u && cl50_previous_generation != 0u) {
        cl50_pending_generation = cl50_previous_generation;
    }
    if (cl50_pending_generation != 0u && LocalBit[60107] && MapVersion == PANEL_MAP_VERSION) {
        if (cl50_pending_generation != cl50_generation) {
            cl50_pending_generation = 0u;
        } else if (BootAck == 0u) {
            BootAck = (unsigned short)(256u + cl50_pending_generation);
            cl50_pending_generation = 0u;
        }
    }
    alarm_previous = current;

    LocalBit[801] = (current != 0u && alarm_muted);
    LocalBit[802] = (current != 0u && !alarm_muted);
    /* Documented native alarm-sound enable. The native alarm service owns
     * its buzzer cadence. Do not write undocumented LB60185.
     */
    LocalBit[60117] = LocalBit[802];
    LocalBit[803] = 1;
    LocalWord[800] = !LocalBit[60107] ? 4 : (MapVersion != PANEL_MAP_VERSION ? 5 : (current == 0u ? 1 : (alarm_muted ? 3 : 2)));


}
